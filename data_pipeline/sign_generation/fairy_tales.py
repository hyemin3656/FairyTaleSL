# 단순 접근용 dict (기존 호환)
FAIRY_TALES = {
    tale["tale_id"]: "\n".join(
        s for seg in tale["segments"] for s in seg["sentences"]
    )
    for tale in FAIRY_TALES_STRUCTURED
}


def get_all_sentences():
    """전체 동화 텍스트를 문장 리스트로 반환"""
    return [
        s
        for tale in FAIRY_TALES_STRUCTURED
        for seg in tale["segments"]
        for s in seg["sentences"]
    ]


def get_tale_sentences(tale_id):
    """특정 동화 문장 리스트 반환"""
    for tale in FAIRY_TALES_STRUCTURED:
        if tale["tale_id"] == tale_id:
            return [s for seg in tale["segments"] for s in seg["sentences"]]
    return []
